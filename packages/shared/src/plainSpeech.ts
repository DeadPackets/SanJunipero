  'Write it the way a person would say it to a friend across a kitchen table: everyday words,' +
  ' short plain sentences, contractions where a person would use them. No semicolons. No colon' +
  ' or dash for effect. Never "nothing changes between them", "and yet", or a set of three for' +
  ' rhythm. No poetic pictures and no summing-up at the end. Say what happened and who did it.' +
  ' If a line would sound odd read out loud, say it the plain way instead.'
